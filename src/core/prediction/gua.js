// 数据 → 查找表：'上卦-下卦' → 卦信息
const GUA_MAP = new Map();
RAW64.forEach(([upper, lower, name, text, temper]) => {
  GUA_MAP.set(`${upper}-${lower}`, { name, text, temper });
});

// 八卦三爻位（初爻→上爻，1 = 阳爻）
const TRIGRAM_BITS = {
  1: [1, 1, 1], // 乾
  2: [1, 1, 0], // 兑
  3: [1, 0, 1], // 离
  4: [1, 0, 0], // 震
  5: [0, 1, 1], // 巽
  6: [0, 1, 0], // 坎
  7: [0, 0, 1], // 艮
  8: [0, 0, 0], // 坤
};

// 爻位组合 → 八卦数
const BITS_TO_TRIGRAM = new Map();
Object.entries(TRIGRAM_BITS).forEach(([num, bits]) => {
  BITS_TO_TRIGRAM.set(bits.join(''), Number(num));
});

/**
 * 梅花易数起卦
 * 年支序数：子1…亥12；月、日用公历（文档注明简化）；时支序数：子1…亥12
 * 上卦 = (年+月+日) mod 8；下卦 = (月+日+时) mod 8；动爻 = (年+月+日+时) mod 6 + 1
 * @param {Date} now 起局时刻
 * @returns {{upper: number, lower: number, moving: number}}
 */
export function castGua(now) {
  const yearBranch = now.getFullYear() % 12; // 简化：公历年 mod 12（子年为 0）
  const yearNum = ((yearBranch + 11) % 12) + 1; // 映射到 子1…亥12
  const monthNum = now.getMonth() + 1;
  const dayNum = now.getDate();
  const hourIdx = Math.floor(((now.getHours() + 1) % 24) / 2); // 0=子…11=亥
  const hourNum = hourIdx + 1;

  const upper = ((yearNum + monthNum + dayNum) % 8) || 8;
  const lower = ((monthNum + dayNum + hourNum) % 8) || 8;
  const moving = ((yearNum + monthNum + dayNum + hourNum) % 6) + 1;
  return { upper, lower, moving };
}

/**
 * 由动爻求变卦
 * @param {number} upper 上卦数 1–8
 * @param {number} lower 下卦数 1–8
 * @param {number} moving 动爻 1–6（初爻为 1）
 * @returns {{upper: number, lower: number}} 变卦上下卦数
 */
export function changedGua(upper, lower, moving) {
  const lowerBits = [...TRIGRAM_BITS[lower]];
  const upperBits = [...TRIGRAM_BITS[upper]];
  if (moving <= 3) {
    lowerBits[moving - 1] = lowerBits[moving - 1] === 1 ? 0 : 1;
  } else {
    upperBits[moving - 4] = upperBits[moving - 4] === 1 ? 0 : 1;
  }
  return {
    upper: BITS_TO_TRIGRAM.get(upperBits.join('')),
    lower: BITS_TO_TRIGRAM.get(lowerBits.join('')),
  };
}

/**
 * 查卦
 * @param {number} upper 上卦数
 * @param {number} lower 下卦数
 * @returns {{name: string, text: string, temper: string}|undefined}
 */
export function lookupGua(upper, lower) {
  return GUA_MAP.get(`${upper}-${lower}`);
}
